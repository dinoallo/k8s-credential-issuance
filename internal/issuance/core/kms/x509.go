const (
	PurposeCACertificate         = "ca-certificate"
	PurposeEtcdPeerCertificate   = "etcd-peer-certificate"
	PurposeEtcdClientCertificate = "etcd-client-certificate"
	AlgorithmRSASHA256           = "RSA-SHA256"
	AlgorithmRSASHA384           = "RSA-SHA384"
	AlgorithmRSASHA512           = "RSA-SHA512"
	AlgorithmECDSASHA256         = "ECDSA-SHA256"
	AlgorithmECDSASHA384         = "ECDSA-SHA384"
	AlgorithmECDSASHA512         = "ECDSA-SHA512"
	AlgorithmEd25519             = "Ed25519"
)

// CertificateIntent is the only X.509 material accepted by the local
// development backend. It is generated by a domain plugin after CSR/profile
// validation; it is not a caller-supplied x509.Certificate template.
type CertificateIntent struct {
	CSRDER            []byte               `json:"csr_der"`
	Profile           string               `json:"profile"`
	SignerName        string               `json:"signer_name,omitempty"`
	Subject           grantapi.X509Subject `json:"subject"`
	DNSNames          []string             `json:"dns_names,omitempty"`
	IPAddresses       []string             `json:"ip_addresses,omitempty"`
	URIs              []string             `json:"uris,omitempty"`
	KeyUsages         []string             `json:"key_usages"`
	ExtendedKeyUsages []string             `json:"extended_key_usages"`
	NotBefore         int64                `json:"not_before"`
	NotAfter          int64                `json:"not_after"`
}

func NewCertificateIntent(domain grantapi.Domain, purpose, keyID, generation, algorithm, operationID string, value CertificateIntent) (SigningIntent, error) {
	if domain != grantapi.DomainCA && domain != grantapi.DomainEtcd {
		return SigningIntent{}, fmt.Errorf("certificate intents are only valid for CA and etcd")
	}
	if purpose != PurposeCACertificate && purpose != PurposeEtcdPeerCertificate && purpose != PurposeEtcdClientCertificate {
		return SigningIntent{}, fmt.Errorf("unsupported certificate KMS purpose %q", purpose)
	}
	payload, err := canonical.Marshal(value)
	if err != nil {
		return SigningIntent{}, fmt.Errorf("canonicalize certificate intent: %w", err)
	}
	return NewIntent(domain, purpose, keyID, generation, algorithm, operationID, payload)
}

func DecodeCertificateIntent(payload []byte) (CertificateIntent, error) {
	canonicalPayload, err := canonical.Canonicalize(payload)
	if err != nil {
		return CertificateIntent{}, err
	}
	var value CertificateIntent
	decoder := json.NewDecoder(bytes.NewReader(canonicalPayload))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&value); err != nil {
		return CertificateIntent{}, fmt.Errorf("decode certificate intent: %w", err)
	}
	if len(value.CSRDER) == 0 || value.Profile == "" || value.NotBefore <= 0 || value.NotAfter <= value.NotBefore {
		return CertificateIntent{}, fmt.Errorf("certificate intent is incomplete")
	}
	return value, nil
}

// X509Issuer holds the intermediate used by the constrained development
// backend. Chain may contain the intermediate's ancestors; self-signed roots
// are always removed from the returned artifact.
type X509Issuer struct {
	Certificate *x509.Certificate
	PrivateKey  crypto.PrivateKey
	Chain       []*x509.Certificate
}

// LocalX509Backend is deliberately a test/development adapter. Production
// deployments replace it with an HSM/KMS adapter implementing the same
// constrained intent contract; this backend never exposes a generic byte
// signing method to callers.
type LocalX509Backend struct {
	issuers map[string]X509Issuer
}

// HTTPX509Backend is the production-facing shape of the X.509 KMS adapter.
// The remote endpoint receives a typed certificate intent and never a generic
// byte-sign request.
type HTTPX509Backend struct {
	Endpoint   string
	HTTPClient *http.Client
	MaxBody    int64
}

func (b *HTTPX509Backend) Sign(ctx context.Context, policy Policy, intent SigningIntent) (Artifact, error) {
	if b == nil || b.Endpoint == "" || policy.KeyRef == "" {
		return Artifact{}, fmt.Errorf("HTTP X.509 KMS backend is not configured")
	}
	value, err := DecodeCertificateIntent(intent.Payload)
	if err != nil {
		return Artifact{}, fmt.Errorf("%w: %v", ErrPolicyDenied, err)
	}
	if ctx == nil {
		ctx = context.Background()
	}
	body, err := json.Marshal(map[string]any{"certificate_intent": value, "key_ref": policy.KeyRef, "key_id": policy.KeyID, "operation_id": intent.OperationID, "payload_digest": intent.PayloadDigest, "purpose": policy.Purpose, "profile": policy.Profile})
	if err != nil {
		return Artifact{}, err
	}
	request, err := http.NewRequestWithContext(ctx, http.MethodPost, strings.TrimRight(b.Endpoint, "/")+"/v1/sign-certificate", bytes.NewReader(body))
	if err != nil {
		return Artifact{}, err
	}
	request.Header.Set("Content-Type", "application/json")
	response, err := copyHTTPClient(b.HTTPClient).Do(request)
	if err != nil {
		return Artifact{}, err
	}
	defer response.Body.Close()
	maxBody := b.MaxBody
	if maxBody <= 0 {
		maxBody = 2 << 20
	}
	data, err := io.ReadAll(io.LimitReader(response.Body, maxBody+1))
	if err != nil {
		return Artifact{}, err
	}
	if int64(len(data)) > maxBody {
		return Artifact{}, fmt.Errorf("KMS certificate response exceeds size limit")
	}
	if response.StatusCode < 200 || response.StatusCode >= 300 {
		return Artifact{}, fmt.Errorf("KMS returned HTTP %s", response.Status)
	}
	var result struct {
		Certificate   []byte `json:"certificate"`
		KeyID         string `json:"key_id"`
		Generation    string `json:"generation"`
		Algorithm     string `json:"algorithm"`
		PayloadDigest string `json:"payload_digest"`
	}
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&result); err != nil || len(result.Certificate) == 0 {
		return Artifact{}, fmt.Errorf("KMS returned no certificate")
	}
	if result.KeyID != policy.KeyID || result.Generation != policy.Generation || result.Algorithm != policy.Algorithm || result.PayloadDigest != intent.PayloadDigest {
		return Artifact{}, fmt.Errorf("%w: KMS certificate metadata mismatch", ErrBadArtifact)
	}
	if _, err := ValidateCertificateChain(result.Certificate); err != nil {
		return Artifact{}, err
	}
	return Artifact{Value: result.Certificate, KeyID: result.KeyID, Generation: result.Generation, Algorithm: result.Algorithm, PayloadDigest: result.PayloadDigest}, nil
}

func (b *HTTPX509Backend) PublicJWK(ctx context.Context, policy Policy) (map[string]any, error) {
	if b == nil || b.Endpoint == "" || policy.KeyRef == "" {
		return nil, fmt.Errorf("HTTP X.509 KMS backend is not configured")
	}
	endpoint, err := url.Parse(strings.TrimRight(b.Endpoint, "/") + "/v1/keys/" + url.PathEscape(policy.KeyRef))
	if err != nil {
		return nil, err
	}
	query := endpoint.Query()
	query.Set("algorithm", policy.Algorithm)
	query.Set("key_id", policy.KeyID)
	endpoint.RawQuery = query.Encode()
	if ctx == nil {
		ctx = context.Background()
	}
	request, err := http.NewRequestWithContext(ctx, http.MethodGet, endpoint.String(), nil)
	if err != nil {
		return nil, err
	}
	response, err := copyHTTPClient(b.HTTPClient).Do(request)
	if err != nil {
		return nil, err
	}
	defer response.Body.Close()
	if response.StatusCode < 200 || response.StatusCode >= 300 {
		return nil, fmt.Errorf("KMS returned HTTP %s", response.Status)
	}
	var value map[string]any
	if err := json.NewDecoder(io.LimitReader(response.Body, 1<<20)).Decode(&value); err != nil {
		return nil, err
	}
	if value["kid"] != policy.KeyID || value["alg"] != policy.Algorithm {
		return nil, fmt.Errorf("KMS returned a public key outside the configured policy")
	}
	return value, nil
}

func NewLocalX509Backend(policies []Policy, issuers map[string]X509Issuer) (*LocalX509Backend, error) {
	if len(policies) == 0 || len(issuers) == 0 {
		return nil, fmt.Errorf("X.509 backend requires policies and issuers")
	}
	copyIssuers := make(map[string]X509Issuer, len(issuers))
	for generation, issuer := range issuers {
		if issuer.Certificate == nil || issuer.PrivateKey == nil {
			return nil, fmt.Errorf("X.509 issuer %q is incomplete", generation)
		}
		if !issuer.Certificate.IsCA {
			return nil, fmt.Errorf("X.509 issuer %q is not a CA certificate", generation)
		}
		if isSelfSigned(issuer.Certificate) {
			return nil, fmt.Errorf("X.509 issuer %q must be an intermediate, not a root", generation)
		}
		if _, ok := issuer.PrivateKey.(crypto.Signer); !ok {
			return nil, fmt.Errorf("X.509 issuer %q key is not a signer", generation)
		}
		copyIssuers[generation] = issuer
	}
	return &LocalX509Backend{issuers: copyIssuers}, nil
}

func (b *LocalX509Backend) Sign(_ context.Context, policy Policy, intent SigningIntent) (Artifact, error) {
	if b == nil {
		return Artifact{}, fmt.Errorf("X.509 backend is not configured")
	}
	if policy.Domain != grantapi.DomainCA && policy.Domain != grantapi.DomainEtcd || policy.Purpose == PurposeServiceAccountJWT {
		return Artifact{}, fmt.Errorf("%w: policy is not an X.509 policy", ErrPolicyDenied)
	}
	if intent.Purpose != policy.Purpose {
		return Artifact{}, fmt.Errorf("%w: X.509 purpose mismatch", ErrPolicyDenied)
	}
	certificateIntent, err := DecodeCertificateIntent(intent.Payload)
	if err != nil {
		return Artifact{}, fmt.Errorf("%w: %v", ErrPolicyDenied, err)
	}
	if policy.Profile != "" && certificateIntent.Profile != policy.Profile {
		return Artifact{}, fmt.Errorf("%w: profile is not allowed by the KMS policy", ErrPolicyDenied)
	}
	if policy.SignerName != "" && certificateIntent.SignerName != policy.SignerName {
		return Artifact{}, fmt.Errorf("%w: signer name is not allowed by the KMS policy", ErrPolicyDenied)
	}
	if err := validateX509Policy(policy, certificateIntent); err != nil {
		return Artifact{}, fmt.Errorf("%w: %v", ErrPolicyDenied, err)
	}
	issuer, ok := b.issuers[policy.Generation]
	if !ok {
		return Artifact{}, fmt.Errorf("X.509 issuer for generation %q is unavailable", policy.Generation)
	}
	request, err := x509.ParseCertificateRequest(certificateIntent.CSRDER)
	if err != nil || request.CheckSignature() != nil {
		return Artifact{}, fmt.Errorf("%w: CSR proof of possession is invalid", ErrPolicyDenied)
	}
	if err := validateCSRIdentity(request, certificateIntent); err != nil {
		return Artifact{}, fmt.Errorf("%w: CSR identity does not match certificate intent: %v", ErrPolicyDenied, err)
	}
	publicDER, err := x509.MarshalPKIXPublicKey(request.PublicKey)
	if err != nil {
		return Artifact{}, err
	}
	if len(publicDER) == 0 {
		return Artifact{}, fmt.Errorf("CSR public key is empty")
	}
	if err := validateIssuerKey(issuer); err != nil {
		return Artifact{}, err
	}
	if expected := certificateAlgorithm(issuer.PrivateKey); expected == "" || expected != policy.Algorithm {
		return Artifact{}, fmt.Errorf("%w: issuer algorithm does not match policy", ErrPolicyDenied)
	}
	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 120))
	if err != nil {
		return Artifact{}, err
	}
	template, err := certificateTemplate(certificateIntent, serial, issuer.Certificate)
	if err != nil {
		return Artifact{}, err
	}
	der, err := x509.CreateCertificate(rand.Reader, template, issuer.Certificate, request.PublicKey, issuer.PrivateKey)
	if err != nil {
		return Artifact{}, fmt.Errorf("create certificate: %w", err)
	}
	if _, err := x509.ParseCertificate(der); err != nil {
		return Artifact{}, err
	}
	chain := append([]*x509.Certificate{issuer.Certificate}, issuer.Chain...)
	value := pemEncodeChain(der, chain)
	if _, err := ValidateCertificateChain(value); err != nil {
		return Artifact{}, err
	}
	return Artifact{Value: value, KeyID: policy.KeyID, Generation: policy.Generation, Algorithm: policy.Algorithm, PayloadDigest: intent.PayloadDigest}, nil
}

func (b *LocalX509Backend) PublicJWK(_ context.Context, policy Policy) (map[string]any, error) {
	if b == nil {
		return nil, fmt.Errorf("X.509 backend is not configured")
	}
	issuer, ok := b.issuers[policy.Generation]
	if !ok {
		return nil, fmt.Errorf("X.509 issuer for generation %q is unavailable", policy.Generation)
	}
	digest := sha256.Sum256(issuer.Certificate.Raw)
	return map[string]any{"kty": "X.509", "kid": policy.KeyID, "alg": policy.Algorithm, "use": "cert-sign", "certificate_sha256": fmt.Sprintf("sha256:%x", digest[:])}, nil
}

func validateX509Policy(policy Policy, value CertificateIntent) error {
	if value.NotAfter-value.NotBefore <= 0 {
		return fmt.Errorf("certificate lifetime is invalid")
	}
	if policy.MaxLifetime > 0 && time.Duration(value.NotAfter-value.NotBefore)*time.Second > policy.MaxLifetime {
		return fmt.Errorf("certificate lifetime exceeds KMS policy")
	}
	if !sortedUnique(value.KeyUsages) || !sortedUnique(value.ExtendedKeyUsages) {
		return fmt.Errorf("certificate usage values are not sorted and unique")
	}
	if len(policy.AllowedKeyUsages) > 0 && !subset(value.KeyUsages, policy.AllowedKeyUsages) {
		return fmt.Errorf("certificate key usage is outside the KMS policy")
	}
	if len(policy.AllowedExtendedKeyUsages) > 0 && !subset(value.ExtendedKeyUsages, policy.AllowedExtendedKeyUsages) {
		return fmt.Errorf("certificate extended key usage is outside the KMS policy")
	}
	for _, required := range policy.RequiredKeyUsages {
		if !contains(value.KeyUsages, required) {
			return fmt.Errorf("required key usage %q is absent", required)
		}
	}
	for _, required := range policy.RequiredExtendedKeyUsages {
		if !contains(value.ExtendedKeyUsages, required) {
			return fmt.Errorf("required extended key usage %q is absent", required)
		}
	}
	return nil
}

func validateIssuerKey(issuer X509Issuer) error {
	signer, ok := issuer.PrivateKey.(crypto.Signer)
	if !ok {
		return fmt.Errorf("issuer key is not a crypto.Signer")
	}
	actual, err := x509.MarshalPKIXPublicKey(signer.Public())
	if err != nil {
		return err
	}
	want, err := x509.MarshalPKIXPublicKey(issuer.Certificate.PublicKey)
	if err != nil || string(actual) != string(want) {
		return fmt.Errorf("issuer private key does not match issuer certificate")
	}
	return nil
}

func certificateAlgorithm(key crypto.PrivateKey) string {
	switch value := key.(type) {
	case *rsa.PrivateKey:
		if value.N != nil && value.N.BitLen() >= 2048 {
			return AlgorithmRSASHA256
		}
	case *ecdsa.PrivateKey:
		switch value.Curve {
		case elliptic.P256():
			return AlgorithmECDSASHA256
		case elliptic.P384():
			return AlgorithmECDSASHA384
		case elliptic.P521():
			return AlgorithmECDSASHA512
		}
	case ed25519.PrivateKey:
		return AlgorithmEd25519
	}
	return ""
}

func certificateTemplate(value CertificateIntent, serial *big.Int, issuer *x509.Certificate) (*x509.Certificate, error) {
	keyUsage, err := keyUsage(value.KeyUsages)
	if err != nil {
		return nil, err
	}
	extUsage, err := extKeyUsage(value.ExtendedKeyUsages)
	if err != nil {
		return nil, err
	}
	return &x509.Certificate{
		SerialNumber: serial, Subject: pkix.Name{CommonName: value.Subject.CommonName, SerialNumber: value.Subject.SerialNumber,
			Country: value.Subject.Country, Locality: value.Subject.Locality, Province: value.Subject.Province,
			StreetAddress: value.Subject.StreetAddress, PostalCode: value.Subject.PostalCode,
			Organization: value.Subject.Organization, OrganizationalUnit: value.Subject.OrganizationalUnit},
		DNSNames: append([]string(nil), value.DNSNames...), IPAddresses: parseIPs(value.IPAddresses), URIs: parseURIs(value.URIs),
		KeyUsage: keyUsage, ExtKeyUsage: extUsage, BasicConstraintsValid: true, IsCA: false,
		NotBefore: time.Unix(value.NotBefore, 0).UTC(), NotAfter: time.Unix(value.NotAfter, 0).UTC(),
		AuthorityKeyId: issuer.SubjectKeyId, SubjectKeyId: subjectKeyID(value.Subject),
	}, nil
}

func validateCSRIdentity(request *x509.CertificateRequest, value CertificateIntent) error {
	if request == nil {
		return fmt.Errorf("CSR is nil")
	}
	subject := value.Subject
	requestSubject := request.Subject
	if requestSubject.CommonName != subject.CommonName || requestSubject.SerialNumber != subject.SerialNumber || !equalSorted(requestSubject.Country, subject.Country) || !equalSorted(requestSubject.Locality, subject.Locality) || !equalSorted(requestSubject.Province, subject.Province) || !equalSorted(requestSubject.StreetAddress, subject.StreetAddress) || !equalSorted(requestSubject.PostalCode, subject.PostalCode) || !equalSorted(requestSubject.Organization, subject.Organization) || !equalSorted(requestSubject.OrganizationalUnit, subject.OrganizationalUnit) {
		return fmt.Errorf("subject mismatch")
	}
	dns := make([]string, 0, len(request.DNSNames))
	for _, value := range request.DNSNames {
		dns = append(dns, strings.ToLower(value))
	}
	if !equalSorted(dns, value.DNSNames) {
		return fmt.Errorf("DNS SAN mismatch")
	}
	ips := make([]string, 0, len(request.IPAddresses))
	for _, value := range request.IPAddresses {
		ips = append(ips, value.String())
	}
	if !equalSorted(ips, value.IPAddresses) {
		return fmt.Errorf("IP SAN mismatch")
	}
	uris := make([]string, 0, len(request.URIs))
	for _, uri := range request.URIs {
		uris = append(uris, uri.String())
	}
	if !equalSorted(uris, value.URIs) {
		return fmt.Errorf("URI SAN mismatch")
	}
	return nil
}

func equalSorted(left, right []string) bool {
	left = append([]string(nil), left...)
	right = append([]string(nil), right...)
	sort.Strings(left)
	sort.Strings(right)
	if len(left) != len(right) {
		return false
	}
	for index := range left {
		if left[index] != right[index] {
			return false
		}
	}
	return true
}

func keyUsage(values []string) (x509.KeyUsage, error) {
	var result x509.KeyUsage
	for _, value := range values {
		switch value {
		case "digitalSignature":
			result |= x509.KeyUsageDigitalSignature
		case "contentCommitment":
			result |= x509.KeyUsageContentCommitment
		case "keyEncipherment":
			result |= x509.KeyUsageKeyEncipherment
		case "dataEncipherment":
			result |= x509.KeyUsageDataEncipherment
		case "keyAgreement":
			result |= x509.KeyUsageKeyAgreement
		case "certSign":
			result |= x509.KeyUsageCertSign
		case "crlSign":
			result |= x509.KeyUsageCRLSign
		case "encipherOnly":
			result |= x509.KeyUsageEncipherOnly
		case "decipherOnly":
			result |= x509.KeyUsageDecipherOnly
		default:
			return 0, fmt.Errorf("unsupported key usage %q", value)
		}
	}
	return result, nil
}

func extKeyUsage(values []string) ([]x509.ExtKeyUsage, error) {
	result := make([]x509.ExtKeyUsage, 0, len(values))
	for _, value := range values {
		switch value {
		case "clientAuth":
			result = append(result, x509.ExtKeyUsageClientAuth)
		case "serverAuth":
			result = append(result, x509.ExtKeyUsageServerAuth)
		case "codeSigning":
			result = append(result, x509.ExtKeyUsageCodeSigning)
		default:
			return nil, fmt.Errorf("unsupported extended key usage %q", value)
		}
	}
	return result, nil
}

func parseIPs(values []string) []net.IP {
	result := make([]net.IP, 0, len(values))
	for _, value := range values {
		if parsed := net.ParseIP(value); parsed != nil {
			result = append(result, parsed)
		}
	}
	return result
}

func parseURIs(values []string) []*url.URL {
	result := make([]*url.URL, 0, len(values))
	for _, value := range values {
		if parsed, err := url.Parse(value); err == nil {
			result = append(result, parsed)
		}
	}
	return result
}

func subjectKeyID(subject grantapi.X509Subject) []byte {
	hash := sha256.New()
	hash.Write([]byte(subject.CommonName))
	for _, value := range subject.Organization {
		hash.Write([]byte{0})
		hash.Write([]byte(value))
	}
	return hash.Sum(nil)[:20]
}

func pemEncodeChain(leaf []byte, chain []*x509.Certificate) []byte {
	result := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: leaf})
	for _, certificate := range chain {
		if certificate == nil || isSelfSigned(certificate) {
			continue
		}
		result = append(result, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: certificate.Raw})...)
	}
	return result
}

// ValidateCertificateChain verifies the leaf-first response contract. It
// rejects self-signed roots, which are trust-bundle material and must not be
// returned through CSR status or a direct certificate response.
func ValidateCertificateChain(data []byte) ([]*x509.Certificate, error) {
	var certificates []*x509.Certificate
	rest := data
	for len(rest) > 0 {
		block, next := pem.Decode(rest)
		if block == nil || block.Type != "CERTIFICATE" || len(block.Bytes) == 0 {
			return nil, fmt.Errorf("certificate chain contains invalid PEM")
		}
		certificate, err := x509.ParseCertificate(block.Bytes)
		if err != nil {
			return nil, fmt.Errorf("parse certificate chain: %w", err)
		}
		certificates = append(certificates, certificate)
		rest = next
	}
	if len(certificates) < 2 || certificates[0].IsCA {
		return nil, fmt.Errorf("certificate response must contain a leaf followed by an intermediate")
	}
	for index := 1; index < len(certificates); index++ {
		if isSelfSigned(certificates[index]) {
			return nil, fmt.Errorf("certificate response contains a root certificate")
		}
		if err := certificates[index-1].CheckSignatureFrom(certificates[index]); err != nil {
			return nil, fmt.Errorf("certificate chain is not ordered leaf-first: %w", err)
		}
	}
	return certificates, nil
}

func isSelfSigned(certificate *x509.Certificate) bool {
	if certificate == nil || !certificate.IsCA || string(certificate.RawSubject) != string(certificate.RawIssuer) {
		return false
	}
	return certificate.CheckSignatureFrom(certificate) == nil
}

func sortedUnique(values []string) bool {
	for i, value := range values {
		if value == "" || i > 0 && values[i-1] >= value {
			return false
		}
	}
	return true
}

func subset(values, allowed []string) bool {
	allowedSet := make(map[string]bool, len(allowed))
	for _, value := range allowed {
		allowedSet[value] = true
	}
	for _, value := range values {
		if !allowedSet[value] {
			return false
		}
	}
	return true
}

func contains(values []string, target string) bool {
	for _, value := range values {
		if value == target {
			return true
		}
	}
	return false
}
